// Generates supabase/seed.sql from src/data/seed.js so both modes share one dataset.
// Usage: npm run seed:sql
import { SEED_MERCHANTS, SEED_HIGHLIGHTS } from '../src/data/seed.js'

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => (a?.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`)

const rows = SEED_MERCHANTS.map((m) =>
  `  (${[q(m.id), q(m.name), q(m.district), q(m.town), q(m.category), q(m.description),
    arr(m.products), arr(m.tags), q(m.open_time), q(m.close_time), q(m.open_days),
    m.lat, m.lng, q(m.emoji), 'true', 'true'].join(', ')})`
)

const hl = SEED_HIGHLIGHTS.map((h) => `  (${[q(h.district), q(h.title), q(h.summary), 'true'].join(', ')})`)

console.log(`-- GENERATED by scripts/gen-seed.mjs. Do not edit by hand.
-- Sample data, clearly labeled in the UI. Replace with real merchants after owner consent.

insert into public.merchants
  (id, name, district, town, category, description, products, tags,
   open_time, close_time, open_days, lat, lng, emoji, is_sample, is_published)
values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, description = excluded.description, products = excluded.products,
  tags = excluded.tags, open_time = excluded.open_time, close_time = excluded.close_time,
  open_days = excluded.open_days, lat = excluded.lat, lng = excluded.lng;

delete from public.highlights where is_sample;
insert into public.highlights (district, title, summary, is_sample)
values
${hl.join(',\n')};
`)
